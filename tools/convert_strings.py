#!/usr/bin/env python3
"""Generate Android strings.xml (all six languages) from the iOS string catalogue.

The iOS app's Localizable.xcstrings is the single source of copy. Re-run this after
the iOS catalogue changes:

    python3 tools/convert_strings.py ../HisaabWiseIOS/HisaabWise/HisaabWise/Resources/Localizable.xcstrings

Key mapping: the iOS key "home.greeting %@ %@" becomes R.string.home_greeting.
Format specifiers: %@ -> %s, %1$@ -> %1$s, %lld -> %d. Positional arguments are
numbered so translations may reorder them.
"""
import json
import os
import re
import sys
from xml.sax.saxutils import escape

LOCALES = {"en": "values", "ar": "values-ar", "hi": "values-hi",
           "fil": "values-b+fil", "ne": "values-ne", "ur": "values-ur"}
HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "app", "src", "main", "res")


def resource_name(key: str) -> str:
    base = key.split(" ")[0]
    name = re.sub(r"[^A-Za-z0-9_]", "_", base)
    return name


SPEC = re.compile(r"%(\d+\$)?(@|lld|ld|d|f|\.\df|s)")


def android_value(value: str) -> tuple[str, bool]:
    count = len([m for m in SPEC.finditer(value)])
    index = 0

    def repl(m):
        nonlocal index
        index += 1
        pos = m.group(1) or (f"{index}$" if count > 1 else "")
        kind = m.group(2)
        conv = {"@": "s", "lld": "d", "ld": "d", "d": "d", "s": "s"}.get(kind, kind)
        return f"%{pos}{conv}"

    # Literal percent signs that are not specifiers must be doubled when formatted.
    out = SPEC.sub(repl, value.replace("%%", "\u0000"))
    formatted = count > 0
    if formatted:
        out = re.sub(r"%(?!(\d+\$)?(s|d|\.\df|f))", "%%", out)
    out = out.replace("\u0000", "%%")
    out = escape(out)
    out = out.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    out = out.replace("\n", "\\n")
    if out.startswith("@") or out.startswith("?"):
        out = "\\" + out
    return out, formatted


def main(path: str) -> None:
    catalogue = json.load(open(path, encoding="utf-8"))
    strings = catalogue["strings"]
    seen: dict[str, str] = {}
    for key in strings:
        name = resource_name(key)
        if name in seen and seen[name] != key:
            raise SystemExit(f"collision: {key!r} and {seen[name]!r} both map to {name}")
        seen[name] = key
    for lang, folder in LOCALES.items():
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- GENERATED by tools/convert_strings.py from the iOS Localizable.xcstrings. Do not edit. -->",
                 '<resources xmlns:tools="http://schemas.android.com/tools">']
        for key in sorted(strings):
            locs = strings[key].get("localizations", {})
            unit = (locs.get(lang) or {}).get("stringUnit")
            if unit is None:
                if lang != "en":
                    continue  # falls back to English
                unit = {"value": key}
            value, formatted = android_value(unit["value"])
            attrs = ' formatted="false"' if (not formatted and "%" in value) else ""
            lines.append(f'    <string name="{resource_name(key)}"{attrs}>{value}</string>')
        lines.append("</resources>")
        out_dir = os.path.join(RES, folder)
        os.makedirs(out_dir, exist_ok=True)
        with open(os.path.join(out_dir, "strings_ios.xml"), "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        print(f"{folder}: {len(lines) - 4} strings")


if __name__ == "__main__":
    main(sys.argv[1])
